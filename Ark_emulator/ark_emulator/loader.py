"""Data loading layer for Ark_emulator.

Consolidates the reverse-engineered data sources under
``ark_parser/enemy/data`` into in-memory structures consumed by the
simulation. All files are read-only; nothing here writes game data.

Sources:
  - stage_sim_bundle.json : levels[levelId] {options, runes, enemyDbRefs,
    enemies, routes (no checkpoints), map {rows, cols, cells}, waveTimeline,
    randomSeed}, stages[stageId] -> levelId, enemyRoster[enemyId] -> data
  - levels/<levelId>.json : full original level incl. mapData.tiles and
    routes[].checkpoints (calibration/complete reference)
  - enemy_database.json   : enemyId -> [{level, data}]
  - skill_behavior_catalog.json : enemyId -> skill behaviour params
"""

import io
import json
import os

_DEFAULT_DIR = r"G:\Arknights\ark_parser\enemy\data"
_CHAR_DIR = r"G:\Arknights\ark_parser\character\data"


def _load(path):
    """Load a JSON data file.  Data files may be regenerated by external
    extraction processes; retry briefly when the file is mid-write (the
    parse raises JSONDecodeError), then surface the real error."""
    last = None
    for _ in range(3):
        try:
            with io.open(path, "r", encoding="utf-8") as f:
                return json.load(f)
        except ValueError as ex:      # JSONDecodeError subclasses ValueError
            last = ex
            try:
                import time
                time.sleep(0.4)
            except Exception:
                break
    raise last


# Process-level caches for the heavy merged prefab catalog (each Simulator
# creates its own DataStore; the ~80MB base+current dump must only be
# parsed once per process).
_PREFAB_CATALOG_CACHE = None
_CURRENT_PREFAB_CACHE = None

# Process-level caches for the other heavy per-DataStore loads.  The stage
# bundle (~149MB JSON -> ~750MB in memory) and the raw level assets are
# read-only after parsing; sharing one parsed copy across every Simulator
# in the process keeps the footprint flat instead of growing ~750MB per
# battle (8 parallel scan workers previously spiked >6GB and pushed the
# system into MemoryError / killed unrelated processes).
_BUNDLE_CACHE = {}
_LEVELS_CACHE = {}
_ENV_SYSTEMS_CACHE = None


def _i2f(val):
    """Float bits (int32 stored in JSON) -> float (game blackboard values)."""
    import struct
    try:
        bits = int(val) & 0xFFFFFFFF
        return round(struct.unpack("<f", struct.pack("<I", bits))[0], 4)
    except (TypeError, ValueError, OverflowError):
        return val


# Prefab-key naming variants between enemy_database skill prefabKeys and
# the extracted GameObject names (verified in enm_pfb cabs):
#   cut_tree -> CutTree   (enemy_1512_mcmstr \u4f10\u6728: the prefab is
#                          named CutTree, the db key uses snake_case)
#   BoomAll  -> DeathBoomAll (enemy_1543_cstlrs \u514b\u4e3d\u65af\u817e:
#                          the full-map boom prefab is named DeathBoomAll)
PREFAB_KEY_ALIASES = {
    "cut_tree": "CutTree",
    "cuttree": "CutTree",   # older game builds named the GameObject cuttree
    "BoomAll": "DeathBoomAll",
}


class DataStore:
    """Lazy loader; data is loaded once and cached on first access."""

    # shared raw-level cache (class attribute: one copy per process, the
    # per-instance init below no longer shadows it)
    _levels = _LEVELS_CACHE

    def __init__(self, data_dir=_DEFAULT_DIR):
        self.data_dir = data_dir
        self._bundle = None
        self._enemy_db = None
        self._flying = None
        self._skill_catalog = None
        self._prefab_catalog = None
        self._characters = None
        self._skills = None
        self._op_prefabs = None
        self._char_dir = _CHAR_DIR if data_dir == _DEFAULT_DIR else \
            os.path.join(data_dir, "..", "character", "data")
        self._level_assets = None
        self._overrides = None
        self._prefab_overrides = None
        self._current_prefabs = None
        self._module_stats = None
        self._battle_equip = None
        self._trust = None
        self._go_name = None
        self._op_catalog = None
        self._comp_prefab = None
        self._shared_prefabs = None

    # ---- files ----
    @property
    def bundle(self):
        if self._bundle is None:
            key = os.path.normpath(self.data_dir)
            cached = _BUNDLE_CACHE.get(key)
            if cached is None:
                cached = _load(os.path.join(
                    self.data_dir, "stage_sim_bundle.json"))
                _BUNDLE_CACHE[key] = cached
            self._bundle = cached
        return self._bundle

    @property
    def enemy_database(self):
        if self._enemy_db is None:
            self._enemy_db = _load(os.path.join(self.data_dir, "enemy_database.json"))
        return self._enemy_db

    @property
    def flying_enemy_keys(self):
        """Enemy keys that are airborne (flight units)."""
        if self._flying is None:
            keys = set()
            for k, entries in self.enemy_database.items():
                if not isinstance(entries, list) or not entries:
                    continue
                first = entries[0] if isinstance(entries[0], dict) else {}
                desc = (first.get("data") or {}).get("description") or ""
                if isinstance(desc, str) and \
                        "\u98de\u884c\u5355\u4f4d" in desc:
                    keys.add(k)
            try:
                hb = _load(os.path.join(self.data_dir, "enemy_handbook.json"))
            except Exception:
                hb = {}
            for k, v in hb.items():
                if not isinstance(v, dict):
                    continue
                tags = v.get("13")
                if isinstance(tags, list) and any(
                        "\u98de\u884c" in str(t) for t in tags):
                    keys.add(k)
            self._flying = keys
        return self._flying

    def is_flying_enemy(self, enemy_key):
        if enemy_key in self.flying_enemy_keys:
            return True
        try:
            resolved = self.resolve_enemy_key(enemy_key)
        except Exception:
            resolved = enemy_key
        return resolved in self.flying_enemy_keys

    @property
    def skill_catalog(self):
        if self._skill_catalog is None:
            self._skill_catalog = _load(os.path.join(self.data_dir, "skill_behavior_catalog.json"))
        return self._skill_catalog

    @property
    def prefab_catalog(self):
        """Full skill prefab serialisation (4423 prefabs, 47802 components).
        Keyed by prefabKey; each value is {components:[{class, fields}]}.
        The current-version enemy prefab dump (data_enemy_prefab_catalog_current.json,
        from the 2026-08-01 enm_pfb bundles) is merged on top: same-name
        keys are replaced by the current data, new enemy prefab keys are
        added (e.g. enemy_2138_shdbjg / enemy_2140_shsgzd / enemy_4064_mupenb)."""
        global _PREFAB_CATALOG_CACHE, _CURRENT_PREFAB_CACHE
        if _PREFAB_CATALOG_CACHE is None:
            base_cat = _load(os.path.join(
                self.data_dir, "skill_prefab_catalog.json"))
            merged = dict(base_cat)
            prefs = dict(base_cat.get("prefabs") or {})
            try:
                if _CURRENT_PREFAB_CACHE is None:
                    _CURRENT_PREFAB_CACHE = _load(os.path.join(
                        os.path.dirname(os.path.abspath(__file__)),
                        "data_enemy_prefab_catalog_current.json"))
                cur_prefs = (_CURRENT_PREFAB_CACHE.get("prefabs") or {})
                prefs.update(cur_prefs)
            except Exception:
                pass
            merged["prefabs"] = prefs
            _PREFAB_CATALOG_CACHE = merged
        self._prefab_catalog = _PREFAB_CATALOG_CACHE
        return self._prefab_catalog

    def _resolve_prefab_key(self, prefab_key):
        """Resolve db prefabKey variants to the extracted GameObject name."""
        if prefab_key in PREFAB_KEY_ALIASES:
            return PREFAB_KEY_ALIASES[prefab_key]
        return prefab_key

    def _prefab_override(self, key):
        """Locally extracted prefab components for db prefabKeys that have
        no matching GameObject name in the base catalog (data extracted from
        the current enm_pfb bundles via ArknightsStudioCLI JSON export):
          - Shining   (enemy_2138/2139 \u6c49\u79d1 flare: projectile_
            enemy_shdbjg_shining + enemy_shsmok_disable reveal buff)
          - Countdown (enemy_4064 \u51b3\u80dc\u65f6\u523b\u7403 10s
            countdown buff applier)
        """
        if self._prefab_overrides is None:
            import io as _io
            _p = os.path.join(os.path.dirname(os.path.abspath(__file__)),
                              "data_enemy_prefab_overrides.json")
            try:
                with _io.open(_p, encoding="utf-8") as _f:
                    self._prefab_overrides = json.load(_f)
            except Exception:
                self._prefab_overrides = {}
        return (self._prefab_overrides.get(key) or {}).get("components") or []

    def prefab_components(self, prefab_key):
        """All components of a prefab (list of {class, fields}). Prefab-key
        naming variants (cut_tree/CutTree, BoomAll/DeathBoomAll) resolve
        through PREFAB_KEY_ALIASES; db keys without a matching GameObject
        name fall back to the local override table."""
        key = self._resolve_prefab_key(prefab_key)
        comps = (self.prefab_catalog.get("prefabs") or {}).get(key, {}).get("components")
        if comps:
            return comps
        return self._prefab_override(prefab_key)

    def prefab_ability_fields(self, prefab_key):
        """Merge fields of Ability/AbilityStandard/AttackAbility/ProjectileAbility
        components into one dict (later components override earlier)."""
        out = {}
        for c in self.prefab_components(prefab_key):
            cls = c.get("class", "")
            if cls in ("Ability", "AbilityStandard", "AttackAbility",
                       "ProjectileAbility", "BuffAbility", "CompositeAbility"):
                out.update(c.get("fields") or {})
        return out

    def enemy_prefab_components(self, enemy_key, prefab_key):
        """Prefab components scoped to ONE enemy.

        The extracted catalog merges same-named prefabs used by several
        enemies under one key (e.g. "Invincible" carries the components of
        telex / faust / ymmons / xbmoth... all in one list).  When a merged
        list is detected, the owner's components are located by matching
        buffKeys that contain the enemy's code (enemy_7021_xbmoth ->
        "xbmoth", e.g. enemy_xbmoth_s[mode]) and only the cabins holding
        those components are kept, so a cast only applies the caster's own
        buffs/abilities instead of every enemy's.
        """
        comps = self.prefab_components(prefab_key)
        if len(comps) <= 8:
            return comps
        code = str(enemy_key).split("_", 2)[-1] if enemy_key else ""
        if not code:
            return comps
        # variant suffixes (_2/_3/_a/_b...) belong to the enemy LEVEL, not
        # the code: enemy_9013_acstmk_2's buffKeys mention "acstmk".
        codes = {code}
        tail = code
        while "_" in tail:
            suf = tail.rsplit("_", 1)[1]
            if suf.isdigit() or (len(suf) == 1 and suf.isalpha()):
                tail = tail.rsplit("_", 1)[0]
                codes.add(tail)
            else:
                break
        def _comp_bks(c):
            f = c.get("fields") or {}
            return [str(b.get("buffKey"))
                    for _k in ("_buffs", "_activeBuffs", "_passiveBuffs")
                    for b in (f.get(_k) or [])
                    if isinstance(b, dict) and b.get("buffKey")]
        # if no component can be attributed to this enemy (buffKeys use
        # inherited/shared names, e.g. mpbarr uses mpprme_spawn_mark),
        # keep the whole prefab: dropping would remove its real effects.
        if not any(enemy_key in _comp_bks(c) or
                   any(cd in bk for cd in codes for bk in _comp_bks(c))
                   for c in comps):
            return comps
        out = []
        for c in comps:
            f = c.get("fields") or {}
            bks = _comp_bks(c)
            if not bks:
                # unassignable component (pure ability / selector / anim):
                # keep it - dropping it would remove damage types etc.
                out.append(c)
                continue
            if enemy_key in bks or any(cd in bk
                                       for cd in codes for bk in bks):
                out.append(c)
                continue
            if ("_selfOption" in f or "_startEvent" in f or
                    "_endEvent" in f or "_forceFinishBuffOnCastEnd" in f):
                # capability container (aura / BuffToOwnerDuringAbility):
                # keep conservatively - it drives the caster's own effect
                out.append(c)
                continue
            # else: the component only carries buffs of OTHER enemies
            # sharing the same prefab key - drop it
        return out

    def enemy_prefab_ability_fields(self, enemy_key, prefab_key):
        """prefab_ability_fields scoped to one enemy (see
        enemy_prefab_components for the merged-prefab problem)."""
        out = {}
        for c in self.enemy_prefab_components(enemy_key, prefab_key):
            cls = c.get("class", "")
            if cls in ("Ability", "AbilityStandard", "AttackAbility",
                       "ProjectileAbility", "BuffAbility", "CompositeAbility"):
                out.update(c.get("fields") or {})
        return out

    def synthesize_skill_entry(self, enemy_key, skill):
        """Build a behavior-catalog-style entry straight from the full prefab
        catalog (mirrors ark_parser/enemy/build_skill_behavior.py) for skills
        whose prefabKey is not in skill_behavior_catalog.json but resolves in
        the prefab catalog (e.g. cut_tree -> CutTree, BoomAll -> DeathBoomAll).
        Returns None when the prefab is unavailable."""
        pk = skill.get("prefabKey")
        if not pk:
            return None
        comps = self.prefab_components(pk)
        if not comps:
            return None

        def _find(cls):
            return [c for c in comps if c.get("class") in
                    (cls if isinstance(cls, tuple) else (cls,))]

        eskill = _find("EnemySkill")
        es = {}
        if eskill:
            f = eskill[0].get("fields") or {}
            for k in ("_familyMask", "_maxTriggerTime", "_overwriteInitCooldown",
                      "_ignoreSilence", "_castLikeAttack",
                      "_resetMainAbilityCdWhenCastEnd", "_resetCdWaitFirstPeriod",
                      "_checkParentActive", "_spCost",
                      "_immuneStunWhenAffecting", "_addEnemyIdToSignalId"):
                if k in f:
                    es[k] = f[k]
        abilities = []
        for a in _find(("Ability", "AbilityStandard", "AttackAbility",
                        "ProjectileAbility", "CompositeAbility", "BuffAbility")):
            f = a.get("fields") or {}
            abilities.append({k: f[k] for k in (
                "_waitForAttackEvent", "_timeMode", "_preDelay", "_atkScale",
                "_interuptIfTargetDead", "_selectTargetTiming",
                "_selectTargetSource", "_allowNoTarget", "_alwaysIncludeTarget",
                "_attackBlackboardModeIndex", "_defaultModeIndex",
                "_extraCondition", "_maxTarget", "_onlyRunOnce",
                "_preDelayFactor", "_purposeMask", "_resetCdStrategy")
                if k in f})
        trigger = {}
        trig_ref = (eskill[0].get("fields") or {}).get("_trigger") if eskill else None
        if isinstance(trig_ref, dict):
            pid = trig_ref.get("m_PathID")
            pool = list(comps)
            # inline enemy skills' triggers live in the enemy's own prefab
            # (current catalog carries pathIDs); fall back to it
            if not any(c.get("pathID") == pid for c in pool):
                try:
                    pool += self.prefab_components(enemy_key)
                except Exception:
                    pass
            for c in pool:
                if c.get("pathID") == pid:
                    f = c.get("fields") or {}
                    if any(k in f for k in (
                            "_triggerType", "_targetRange", "_time",
                            "_hpRatio", "_damageTakenRatio", "_interval",
                            "_maxTriggerTime", "_normalSkillOnly",
                            "_condition", "_radius", "_target", "_minHpRatio",
                            "_keepTarget", "_minTargetNum")):
                        trigger = {k: f[k] for k in (
                            "_triggerType", "_targetRange", "_time",
                            "_hpRatio", "_damageTakenRatio", "_condition",
                            "_extraCondition", "_event", "_forcePredict",
                            "_normalSkillOnly", "_maxTriggerTime",
                            "_interval", "_radius", "_target", "_buffKeys",
                            "_minHpRatio", "_keepTarget", "_minTargetNum")
                            if k in f}
                    break
        buff_keys = set()
        for c in comps:
            def _walk(v):
                if isinstance(v, dict):
                    if isinstance(v.get("buffKey"), str) and v["buffKey"]:
                        buff_keys.add(v["buffKey"])
                    if isinstance(v.get("templateKey"), str) and v["templateKey"]:
                        buff_keys.add(v["templateKey"])
                    for x in v.values():
                        _walk(x)
                elif isinstance(v, list):
                    for x in v:
                        _walk(x)
            _walk(c.get("fields") or {})
        return {
            "prefabKey": pk,
            "enemyId": enemy_key,
            "blackboard": skill.get("blackboard"),
            "priority": skill.get("priority"),
            "cooldown": skill.get("cooldown"),
            "initCooldown": skill.get("initCooldown"),
            "spCost": skill.get("spCost"),
            "enemySkill": es,
            "trigger": trigger,
            "abilities": abilities,
            "buffKeys": sorted(buff_keys),
            "_synthesized": True,
        }

