    @staticmethod
    def _module_phases(be):
        """Sorted [(equip_level, phase_dict)] from battle_equip '0' phases,
        skipping malformed entries whose level field is not an int."""
        out = []
        for p in (be.get("0") or []):
            if not isinstance(p, dict):
                continue
            try:
                lv = int(p.get("0") or 0)
            except (TypeError, ValueError):
                continue
            out.append((lv, p))
        return sorted(out, key=lambda item: item[0])

    def module_talent_upgrades(self, module_id, level=3):
        """Module talent blackboard upgrades: list of
        {talent_index (1-based), name, values} for the given module level.

        battle_equip[moduleId]['0'] = phases [{0: level, 1: [entries]}];
        each upgrade entry's '1'[0]['0'] holds candidate dicts with
        '6' = 1-based talent index, '7' = talent name and '10' = ordered
        blackboard values (float bits). candidate[0] is the base module
        value (candidate[1] is the potential-upgraded variant)."""
        if not module_id:
            return []
        be = self.battle_equip.get(module_id)
        if not be:
            return []
        phases = self._module_phases(be)
        best = None
        for _ph_lv, ph in phases:
            if _ph_lv <= max(1, int(level or 1)):
                best = ph
        if best is None:
            return []
        out = []
        for entry in best.get("1") or []:
            lst = (entry or {}).get("1")
            if not isinstance(lst, list) or not lst:
                continue
            inner = lst[0]
            if not isinstance(inner, dict):
                continue
            cands = inner.get("0")
            if not isinstance(cands, list):
                continue
            for c in cands:
                if not isinstance(c, dict) or "6" not in c:
                    continue
                try:
                    ti = int(c.get("6"))
                except (TypeError, ValueError):
                    continue
                vals = []
                _v10 = c.get("10")
                if not isinstance(_v10, list):
                    _v10 = []
                for kv in _v10:
                    if not isinstance(kv, dict) or "1" not in kv:
                        continue
                    try:
                        vals.append(_i2f(int(kv.get("1"))))
                    except (TypeError, ValueError):
                        continue
                out.append({"talent_index": ti, "name": c.get("7"),
                            "values": vals})
        return out

    def module_trait_upgrades(self, module_id, level=3):
        """Module trait (\u7279\u6027) blackboard upgrades: list of
        {values} (one per overrideTraitDataBundle candidate) for the given
        module level.  Same phase selection as module_talent_upgrades;
        each phase part carries the trait bundle under ``6`` with candidates
        in ``6.0`` and the blackboard DataPair list in candidate ``3``
        (e.g. \u54c8\u6d1b\u5fb7 WDM-X: ep_heal_ratio 0.5 -> 0.6 at module
        level 1+)."""
        if not module_id:
            return []
        be = self.battle_equip.get(module_id)
        if not be:
            return []
        phases = self._module_phases(be)
        best = None
        for _ph_lv, ph in phases:
            if _ph_lv <= max(1, int(level or 1)):
                best = ph
        if best is None:
            return []
        out = []
        for part in best.get("1") or []:
            bundle = (part or {}).get("6")
            if not isinstance(bundle, dict):
                continue
            for c in (bundle.get("0") or []):
                if not isinstance(c, dict):
                    continue
                vals = []
                _bb = c.get("3")
                if not isinstance(_bb, list):
                    _bb = []
                for kv in _bb:
                    if not isinstance(kv, dict) or "1" not in kv:
                        continue
                    try:
                        vals.append(_i2f(int(kv.get("1"))))
                    except (TypeError, ValueError):
                        continue
                if vals:
                    out.append({"values": vals})
        return out

    def module_stat_bonus(self, module_id, level=3):
        """Module attribute bonus dict (bb keys: max_hp/atk/def/attack_speed/
        magic_resistance/cost/respawn_time/block_cnt) for the given level, or
        None when the module/level is unknown."""
        if not module_id:
            return None
        m = self.module_stats.get(module_id)
        if not m:
            return None
        phases = sorted(((ph or {}) for ph in (m.get("phases") or [])),
                        key=lambda ph: int(ph.get("level") or 0))
        best = None
        for ph in phases:
            if int(ph.get("level") or 0) <= max(1, int(level or 1)):
                best = ph
        if best is None:
            return None
        return dict(best.get("bb") or {})

    @property
    def character_skills(self):
        """character/data/skills.json (skillId -> {skillId, levels})."""
        if self._skills is None:
            self._skills = _load(os.path.join(self._char_dir, "skills.json"))
        return self._skills

    @property
    def skill_prefab_overrides(self):
        """skillId -> MainSkill.overridePrefabKey (characters.json).

        Token/summon skills often declare an empty runtime prefab override
        (e.g. sktok_phatm2_mndclv_3 -> sktok_empty); component lookups must
        use the override, not the LevelData.prefabId.
        """
        if self._overrides is None:
            self._overrides = {}
            try:
                for c in self.characters.values():
                    for ms in (c.get("skills") or []):
                        sid = ms.get("skillId")
                        ov = ms.get("overridePrefabKey")
                        if sid and ov:
                            self._overrides[sid] = ov
            except Exception:
                self._overrides = {}
        return self._overrides

    @property
    def _go_path_to_name(self):
        """GameObject pathID -> prefab name (from catalog meta; Composite
        Ability `_abilities` PPtrs resolve through this map)."""
        if self._go_name is None:
            self._go_name = {}
            try:
                meta = (self.operator_skill_catalog.get("meta") or {})
                m = meta.get("gameObjectPathIDToName") or {}
                self._go_name = {int(k): v for k, v in m.items()}
            except Exception:
                self._go_name = {}
        return self._go_name

    @property
    def operator_skill_catalog(self):
        """Full operator skill prefab catalog (per-component fields +
        GameObject pathID map)."""
        if self._op_catalog is None:
            p = os.path.join(self._char_dir,
                             "skill_prefab_catalog_operator.json")
            try:
                self._op_catalog = _load(p) if os.path.exists(p) else {}
            except Exception:
                self._op_catalog = {}
        return self._op_catalog

    @property
    def _shared_prefab_names(self):
        """Prefab names referenced by >=3 skills: shared ability templates
        (ExtraAbility0 / Aura / Attack ...) whose fields must not be
        attributed to individual skills."""
        if self._shared_prefabs is None:
            counter = {}
            comp_prefab = self._component_prefab_map
            prefabs = (self.operator_skill_catalog.get("prefabs") or {})
            for name, v in prefabs.items():
                if not (name.startswith("skchr_") or
                        name.startswith("sktok_")):
                    continue
                seen = set()

                def visit(n):
                    if n in seen:
                        return
                    seen.add(n)
                    for c in (prefabs.get(n, {}).get("components") or []):
                        for fk in ("_abilities", "_extraAbilities",
                                   "_wrappedAbilities"):
                            for ref in (c.get("fields", {}).get(fk) or []):
                                pid = (ref or {}).get("m_PathID")
                                sub = comp_prefab.get(pid) \
                                    if pid is not None else None
                                if sub:
                                    counter[sub] = counter.get(sub, 0) + 1
                                    visit(sub)
                visit(name)
            self._shared_prefabs = {k for k, n in counter.items() if n >= 3}
        return self._shared_prefabs

    @property
    def _component_prefab_map(self):
        """MonoBehaviour pathID -> prefab name (CompositeAbility._abilities
        PPtrs reference Ability *components*; their owner prefab is found
        through this map)."""
        if self._comp_prefab is None:
            m = {}
            for name, v in (self.operator_skill_catalog.get(
                    "prefabs") or {}).items():
                for c in (v.get("components") or []):
                    pid = c.get("pathID")
                    if pid is not None:
                        m.setdefault(pid, name)
            self._comp_prefab = m
        return self._comp_prefab

    def operator_prefab_for_skill(self, skill_id):
        """Runtime prefab components for a skill (override-aware),
        including components reachable through CompositeAbility._abilities
        PPtr references (sub-prefabs), deduped by prefab name."""
        ov = self.skill_prefab_overrides.get(skill_id or "")
        root = ov or skill_id or ""
        prefabs = self.operator_skill_prefabs
        comp_prefab = self._component_prefab_map
        shared = self._shared_prefab_names
        out = []
        seen = set()

        # PPtr-list fields that reference other Ability components
        _ABILITY_REF_FIELDS = ("_abilities", "_extraAbilities",
                               "_wrappedAbilities")
        # character code from "skchr_<code>_<n>" / "sktok_<code>..."
        _parts = (skill_id or "").split("_")
        _code = _parts[1] if len(_parts) > 1 else ""

        def _matches_skill(comp):
            """Shared templates carry per-operator assets (e.g. the generic
            'Attack' prefab holds Ling's projectile); only attribute them
            when the projectile key names this skill's operator."""
            pk = comp.get("_projectileKey")
            if not pk:
                return False
            return _code and _code in str(pk)

        def visit(name):
            if not name or name in seen:
                return
            if name in shared:
                # shared building block: include only the components whose
                # projectile belongs to this operator (e.g. horn_s1)
                keep = [c for c in (prefabs.get(name) or [])
                        if _matches_skill(c)]
                if not keep:
                    return
                seen.add(name)
                out.extend(keep)
                return
            seen.add(name)
            comps = prefabs.get(name) or []
            for c in comps:
                out.append(c)
                for fk in _ABILITY_REF_FIELDS:
                    for ref in (c.get(fk) or []):
                        pid = (ref or {}).get("m_PathID")
                        sub = comp_prefab.get(pid) if pid is not None \
                            else None
                        if sub:
                            visit(sub)
        visit(root)
        return out

